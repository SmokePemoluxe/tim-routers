function changelog_html(array $e): string
{
	$h = '<div class="item"><b>' . h($e['ver']) . '</b> <span class="muted">· ' . date('d.m.Y', strtotime($e['date'])) . '</span><ul style="margin:6px 0 0;padding-left:20px">';
	foreach ($e['items'] as [$what, $why]) {
		$h .= '<li style="margin-bottom:4px">' . h($what) . '<br><span class="muted">Зачем: ' . h($why) . '</span></li>';
	}
	return $h . '</ul></div>';
}
